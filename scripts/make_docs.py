"""Rewrite docs/documents_list.md from the loaded database, so the list can never disagree with the data."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import db as dbm, seed

d = dbm.connect(":memory:"); seed.seed(d)
rows = d.execute("SELECT doc_id,doc_type,topic,effective_from,supersedes,language,title FROM documents ORDER BY authority, doc_id").fetchall()
L = ["# Document ID list", "", "%d documents loaded from the supplied kit (`data_kit/data/policies`). Generated by `scripts/make_docs.py`; do not edit by hand." % len(rows), "",
     "| doc_id | type | topic | in force from | replaces | language | title |", "|---|---|---|---|---|---|---|"]
for r in rows:
    L.append("| %s | %s | %s | %s | %s | %s | %s |" % (r["doc_id"], r["doc_type"], r["topic"], r["effective_from"], r["supersedes"] or "-", r["language"], r["title"]))
open(os.path.join(ROOT, "docs", "documents_list.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote docs/documents_list.md with", len(rows), "documents")
